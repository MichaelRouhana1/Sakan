"""Generate backend/ops/osm/normalize_v2.sql (the single source for search_normalize v2).

The Latin fold is a static translate() table so the SQL function is genuinely
IMMUTABLE and does not depend on unaccent.rules. Run: python gen_normalize_sql.py
"""
import pathlib
import unicodedata

MANUAL = {"ø": "o", "đ": "d", "ł": "l", "ı": "i", "ð": "d", "ħ": "h", "ŧ": "t"}


def latin_pairs():
    pairs = {}
    ranges = [(0x00C0, 0x024F), (0x1E00, 0x1EFF)]
    for lo, hi in ranges:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            if not ch.isalpha() or ch != ch.lower():
                continue
            base = unicodedata.normalize("NFD", ch)[0]
            if base != ch and base.isascii() and base.isalpha() and len(unicodedata.normalize("NFD", ch)) > 1:
                pairs[ch] = base
    pairs.update(MANUAL)
    return pairs


def main():
    pairs = latin_pairs()
    src = "".join(pairs)
    dst = "".join(pairs[c] for c in pairs)
    assert len(src) == len(dst)
    # Arabic folds kept identical to 0041, plus Arabic-Indic / Persian digits.
    ar_src = "أإآٱىیكکة٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹"
    ar_dst = "ااااييككه01234567890123456789"
    assert len(ar_src) == len(ar_dst)
    sql = f"""-- GENERATED by gen_normalize_sql.py. Do not edit by hand.
-- search_normalize v2: IMMUTABLE, static Latin fold (no unaccent), Arabic folds,
-- final hamza drop, generic street words ignored. "st" is deliberately NOT generic
-- (St Joseph / St Nicolas). Generic words are dropped only if another token remains.
CREATE OR REPLACE FUNCTION {{{{FN}}}}(value text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE SET search_path = pg_catalog AS $fn$
  SELECT coalesce(
    nullif(btrim(regexp_replace(' ' || t.s || ' ',
      '\\s(?:street|rue|road|rd|avenue|av|شارع|طريق)(?=\\s)', '', 'g')), ''),
    t.s)
  FROM (SELECT btrim(regexp_replace(
      regexp_replace(
        regexp_replace(
          translate(
            replace(replace(replace(lower(regexp_replace(normalize(coalesce(value, ''), NFKC),
              U&'[\\0300-\\036f\\0610-\\061a\\064b-\\065f\\0670\\06d6-\\06ed\\0640\\200b-\\200f\\202a-\\202e\\2066-\\2069\\feff]', '', 'g')),
              'æ', 'ae'), 'œ', 'oe'), 'ß', 'ss'),
            '{src}{ar_src}', '{dst}{ar_dst}'),
          '[^[:alnum:]]+', ' ', 'g'),
        'ء+(\\s|$)', '\\1', 'g'),
      '\\s+', ' ', 'g')) AS s) t
$fn$;
"""
    out = pathlib.Path(__file__).with_name("normalize_v2.sql")
    out.write_text(sql, encoding="utf-8")
    print(f"wrote {out} ({len(pairs)} latin folds)")


if __name__ == "__main__":
    main()
